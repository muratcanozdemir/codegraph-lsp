#!/usr/bin/env bash
# Render a codegraph SVG for one or more repos and link it from each README.
#
# Usage: scripts/codegraph-svg.sh [--root DIR] [--svg PATH] [--pages DIR] REPO...
#   --root DIR    directory to analyse, relative to each repo (default: .)
#   --svg PATH    output path, relative to each repo (default: codegraph.svg)
#   --pages DIR   where per-community SVGs go, relative to each repo (default: docs)
#
# Small graphs are drawn symbol by symbol. Larger ones (see visualise.py --max-nodes) get
# one node per community in PATH, each linking to DIR/NAME-cN.svg (NAME: PATH's file name
# without .svg), which draws that community's symbols with its 5 busiest hubs listed in a
# legend. Earlier DIR/NAME-c*.svg files are replaced.
# Adds a "Call graph" section to REPO/README.md unless it already references the SVG.
# Nothing is committed. Needs graphviz (sfdp) and the LSP server for each repo's language.
set -uo pipefail

cg="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
if [ -x "$cg/.venv/bin/codegraph" ]; then run=("$cg/.venv/bin/codegraph"); else run=(uv run --quiet --project "$cg" codegraph); fi

root=. svg=codegraph.svg pages=docs
while [ $# -gt 0 ]; do
  case "$1" in
    --root) root="$2"; shift 2 ;;
    --svg)  svg="$2";  shift 2 ;;
    --pages) pages="$2"; shift 2 ;;
    -h|--help) sed -n '2,14p' "$0"; exit 0 ;;
    *) break ;;
  esac
done
[ $# -gt 0 ] || { sed -n '2,14p' "$0" >&2; exit 2; }

vis="$cg/scripts/visualise.py"
tmp="$(mktemp -d)"; trap 'rm -rf "$tmp"' EXIT

name="$(basename "${svg%.svg}")"
# overview -> pages, relative to the overview's own directory, for its links
link="$(python3 -c 'import os, sys; print(os.path.relpath(sys.argv[1], sys.argv[2]))' \
  "$pages/$name" "$(dirname "$svg")")-c{id}.svg"

# drill BASE: one BASE-cN.svg per community the overview links to
drill() {
  rm -f "$1"-c*.svg
  local ids c
  ids="$(python3 "$vis" "$tmp/report.json" --drilldowns)" || return 1
  [ -z "$ids" ] || mkdir -p "$(dirname "$1")" || return 1
  for c in $ids; do
    python3 "$vis" "$tmp/report.json" --community "$c" --hubs 5 | sfdp -Tsvg -o "$1-c$c.svg" || return 1
  done
}
rc=0
for repo in "$@"; do
  repo_name="$(basename "$(cd "$repo" && pwd)")"
  mkdir -p "$repo/$(dirname "$svg")"
  if "${run[@]}" "$repo/$root" -o "$tmp/report.json" >/dev/null 2>"$tmp/log" \
     && python3 "$vis" "$tmp/report.json" --link "$link" | sfdp -Tsvg -o "$repo/$svg" \
     && drill "$repo/$pages/$name"; then
    readme="$repo/README.md"
    if [ -f "$readme" ] && ! grep -qF "$svg" "$readme"; then
      printf '\n## Call graph\n\nSymbol-level coupling across the repository, coloured by Leiden community (generated by [codegraph-lsp](https://github.com/muratcanozdemir/codegraph-lsp)):\n\n![Call graph of %s](%s)\n' "$repo_name" "$svg" >> "$readme"
    fi
    echo "ok    $repo/$svg"
  else
    echo "FAIL  $repo: $(tail -1 "$tmp/log")" >&2; rc=1
  fi
done
exit $rc
